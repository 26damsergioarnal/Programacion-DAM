package aprender.numeros;

public class Numeritos {

	public static void main(String[] args) {
		int num;
		num = 7;
		short corto;
		corto = -5;
		byte bite;
		bite = -57;
		long largo;
		largo = 3000000000L;
		
		
		float sencillo;
		double doble;
		doble = 2.5;
		doble = 0.0000000000000;
		doble = 5e-57;
		sencillo = 5.5f;
		System.out.println("el corot vale: " + corto);
		System.out.println("4 + 4 es: " + (4+4));
		
		System.out.println("ignorar");
		System.out.println(doble + sencillo + largo + bite + num);
		
	}

}
