package aprender;

public class NumeroCuentas {
	public static void main(String[] args) {
		int m = 7;
		int n = 5;
		int p = 2;
		
		System.out.println(n + m);
		System.out.println(n - m);
		System.out.println(n / p);
		
		System.out.println(n == 5); // 0.5 tambien es true
		System.out.println(m >= p); //true
		System.out.println(p < -7);
		System.out.println(p != 2); //esto "es igual que"
	}

}
