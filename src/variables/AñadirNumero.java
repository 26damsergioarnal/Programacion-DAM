package variables;

public class AñadirNumero {

	public static void main(String[] args) {
		int numero = 7;
		numero = numero + 3;
		System.out.println(numero);
		//otra manera
		numero += 3;
		System.out.println(numero);
		numero -= 2;
		System.out.println(numero);
		numero *= 5;
		System.out.println(numero);
		numero++; //numero siguiente
		System.out.println(numero);
		numero--; //numero anterior
		System.out.println(numero);

	}

}
